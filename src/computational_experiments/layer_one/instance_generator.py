"""
Generator for the Order-Line allocation instances in `instances.py`.

Instances use the same format as the prototype instances: a list of geometries, each a list of
alternatives `(duration, line_id, priority, due_date)` in solver time (minutes since Monday 06:00,
weekends excluded). An instance "ends at 22:00" of a given day, i.e. it is constructed around a
planted schedule in which every line finishes exactly at 22:00 of that day:

1. For each line, the interval [0, end] is partitioned into consecutive batches (one geometry each).
   The planted line is the geometry's primary alternative.
2. Some geometries get alternatives on other lines with a duration >= the primary duration.
3. Due dates are the next shift boundary (06:00, 14:00, 22:00) at or after the planted finish time,
   plus a random number of shifts of slack, capped at the instance end.
4. Priority geometries (if any) are only chosen among geometries that start at 0 in the planted schedule.

Consequently the planted schedule has makespan == end and zero tardiness. Since alternatives are never
shorter than the primary option, the total work is at least n_lines * end, so the makespan cannot be
smaller than end. The planted schedule is therefore optimal for every weighting of Equation (1):
Z* = w_c * end.

Run this module to regenerate `instances.py`.
"""
import pathlib
import random

DAY = 1440
SHIFT = 480
WEEK = 5 * DAY  # Saturday 06:00 to Monday 06:00 is excluded from solver time

# (name prefix, end in solver time, description, seed base)
INSTANCE_SETS = [
    ("INSTANCE_TUE_2200", 1 * DAY + 2 * SHIFT, "Tuesday 22:00", 100),
    ("INSTANCE_SAT_0600", WEEK, "Saturday 06:00", 500),
    ("INSTANCE_NEXT_SAT_0600", 2 * WEEK, "Saturday 06:00 of the following week", 1000),
]


def generate_instance(end: int, n_lines: int = 3, min_duration: int = 240, max_duration: int = 1440,
                      duration_step: int = 60, p_alternative: float = 0.5, max_alternative_overhead: float = 0.3,
                      max_due_date_slack_shifts: int = 2, n_priority: int = 0, seed: int = 0) -> list:
    rng = random.Random(seed)
    durations_steps = list(range(min_duration, max_duration + 1, duration_step))

    # planted schedule: (start, duration, line) per geometry
    planted = []
    for line in range(n_lines):
        t = 0
        while t < end:
            remaining = end - t
            if remaining <= max_duration and (remaining < 2 * min_duration or rng.random() < 0.5):
                duration = remaining
            else:
                # avoid a final batch shorter than min_duration
                duration = rng.choice([d for d in durations_steps if d <= remaining - min_duration])
            planted.append((t, duration, line))
            t += duration

    priority_candidates = [i for i, (start, _, _) in enumerate(planted) if start == 0]
    priority_idxs = set(rng.sample(priority_candidates, min(n_priority, len(priority_candidates))))

    instance = []
    for idx, (start, duration, line) in enumerate(planted):
        finish = start + duration
        due_date = -(-finish // SHIFT) * SHIFT + rng.randint(0, max_due_date_slack_shifts) * SHIFT
        due_date = min(due_date, end)
        priority = 1 if idx in priority_idxs else 0

        alternatives = [(duration, line, priority, due_date)]
        for other_line in range(n_lines):
            if other_line != line and rng.random() < p_alternative:
                overhead = rng.uniform(0, max_alternative_overhead)
                alt_duration = int(round(duration * (1 + overhead) / 10)) * 10
                alternatives.append((alt_duration, other_line, priority, due_date))
        rng.shuffle(alternatives)
        instance.append(alternatives)

    rng.shuffle(instance)
    return instance


def instance_to_str(name: str, instance: list) -> str:
    lines = [f"{name} = ["]
    for g_idx, alternatives in enumerate(instance):
        sep = "," if g_idx < len(instance) - 1 else ""
        lines.append(f"    # Geometry {g_idx + 1}")
        lines.append(f"    [{', '.join(str(a) for a in alternatives)}]{sep}")
    lines.append("]")
    return "\n".join(lines)


def main(n_variants: int = 5, n_lines: int = 3) -> None:
    blocks = [
        '"""\n'
        'Order-Line allocation instances in solver time (minutes since Monday 06:00, weekends excluded).\n'
        'Each alternative is a tuple (duration, line_id, priority, due_date).\n\n'
        'Each instance is constructed around a planted schedule in which all lines finish exactly at the instance\n'
        'end (Tuesday 22:00, Saturday 06:00, or Saturday 06:00 of the following week), with zero tardiness.\n'
        'The optimal makespan therefore equals END_TIMES[name], and the optimal objective of Equation (1) is\n'
        'w_c * END_TIMES[name] for every weighting.\n\n'
        'Generated by computational_experiments/layer_one/instance_generator.py -- do not edit by hand.\n'
        '"""'
    ]
    names = []
    end_times = {}
    for prefix, end, description, seed_base in INSTANCE_SETS:
        for variant in range(1, n_variants + 1):
            name = f"{prefix}_V{variant}"
            instance = generate_instance(end=end, n_lines=n_lines, seed=seed_base + variant)
            blocks.append(f"# {description} (solver time {end}), {len(instance)} geometries, {n_lines} lines\n"
                          + instance_to_str(name, instance))
            names.append(name)
            end_times[name] = end

    blocks.append("INSTANCES = {\n" + "".join(f'    "{n}": {n},\n' for n in names) + "}")
    blocks.append("END_TIMES = {\n" + "".join(f'    "{n}": {end_times[n]},\n' for n in names) + "}")

    out = pathlib.Path(__file__).parent / "instances.py"
    out.write_text("\n\n\n".join(blocks) + "\n")
    print(f"wrote {len(names)} instances to {out}")


if __name__ == "__main__":
    main()
